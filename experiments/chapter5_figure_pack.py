"""Black-and-white paper figures from measured chapter-5 CSV evidence.

Figures only consume data generated by the study. They do not invent results.
"""
from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

POLICIES = (
    ('confidence_only', 'Confidence only', '///'),
    ('confidence_equal_guardrail', 'Confidence + shared guardrail', 'xxx'),
    ('canonical_risk_with_qc', 'Canonical risk observer', '...'),
)
CONDITIONS = ('clean', 'missing_10pct', 'missing_40pct', 'sensor_noise_2sd')
DISPLAY = {'clean': 'Original rows', 'missing_10pct': '10% missing', 'missing_40pct': '40% missing', 'sensor_noise_2sd': '2 SD noise'}


def _load(path: Path) -> list[dict[str, str]]:
    with path.open('r', encoding='utf-8', newline='') as f:
        rows = list(csv.DictReader(f))
    if not rows:
        raise ValueError('Empty study metrics')
    return rows


def _draw(path: Path, matrix: list[list[float]], y_label: str, title: str, y_top: float) -> Path:
    fig, ax = plt.subplots(figsize=(10.5, 5.2))
    x = np.arange(len(CONDITIONS))
    width = 0.24
    for i, ((_, label, hatch), vals) in enumerate(zip(POLICIES, matrix)):
        rects = ax.bar(x + (i - 1) * width, vals, width,
                       color=['white', '#c9c9c9', '#777777'][i],
                       edgecolor='#222222', linewidth=0.9, hatch=hatch,
                       label=label)
        for rect, val in zip(rects, vals):
            ax.annotate(f'{val:.1f}', (rect.get_x() + rect.get_width()/2, rect.get_height()),
                        xytext=(0, 3), textcoords='offset points', ha='center', fontsize=8)
    ax.set_title(title, fontsize=12)
    ax.set_ylabel(y_label)
    ax.set_xticks(x, [DISPLAY[c] for c in CONDITIONS])
    ax.set_ylim(0, y_top)
    ax.legend(loc='upper right', fontsize=8)
    ax.grid(axis='y', linewidth=0.4, alpha=0.25)
    ax.set_axisbelow(True)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=180)
    fig.savefig(path.with_suffix('.pdf'))
    plt.close(fig)
    return path


def create_figures(csv_path: Path, output_dir: Path) -> list[Path]:
    rows = _load(csv_path)
    observed = defaultdict(list)
    for row in rows:
        observed[(row['policy'], row['perturbation'])].append(row)
    required = {(p, c) for p, _, _ in POLICIES for c in CONDITIONS}
    if not required <= set(observed):
        raise ValueError(f'Missing policy-condition pairs: {required - set(observed)}')
    coverage = []
    flagged = []
    for policy, _, _ in POLICIES:
        coverage.append([100.0 * np.mean([float(r['coverage']) for r in observed[(policy, c)]]) for c in CONDITIONS])
        flagged.append([100.0 * sum(int(r['auto_accepted_with_critical_flag']) for r in observed[(policy, c)]) /
                        max(1, sum(int(r['n']) for r in observed[(policy, c)])) for c in CONDITIONS])
    return [
        _draw(output_dir / 'fig_5_wdbc_auto_accept_coverage.png', coverage,
              'Auto-acceptance coverage, % of objects', 'Held-out WDBC: acceptance coverage across controlled perturbations', 115),
        _draw(output_dir / 'fig_5_wdbc_critical_flag_accept.png', flagged,
              'Accepted with critical QC flag, % of objects', 'Held-out WDBC: critical-flag acceptance (shared-flag control)', 65),
    ]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--csv', type=Path, required=True)
    ap.add_argument('--out', type=Path, required=True)
    args = ap.parse_args()
    for f in create_figures(args.csv, args.out):
        print(f)


if __name__ == '__main__':
    main()
